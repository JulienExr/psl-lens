import { mkdir, readFile, writeFile, rm, mkdtemp, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { FaceLandmarker } from '@mediapipe/tasks-vision';
import { build } from 'esbuild';

const model = 'node_modules/.cache/psl-lens/face_landmarker.task';
const expected = '64184e229b263107bc2b804c6625db1341ff2bb731874b0bcc2fe6544e0bc9ff';
await mkdir(path.dirname(model), { recursive: true });
let bytes;
for (const candidate of [model, 'public/models/face_landmarker.task']) {
  try {
    const candidateBytes = await readFile(candidate);
    if (createHash('sha256').update(candidateBytes).digest('hex') === expected) {
      bytes = candidateBytes;
      break;
    }
  } catch {
    /* The first preparation downloads the pinned model. */
  }
}
if (!bytes) {
  console.log('Downloading MediaPipe face model v1 (3.6 MiB)…');
  const response = await fetch(
    'https://storage.googleapis.com/mediapipe-models/face_landmarker/face_landmarker/float16/1/face_landmarker.task',
    { signal: AbortSignal.timeout(120000) },
  );
  if (!response.ok) throw new Error(`Model download failed: ${response.status}`);
  bytes = Buffer.from(await response.arrayBuffer());
  if (createHash('sha256').update(bytes).digest('hex') !== expected)
    throw new Error('Model checksum mismatch');
}
await writeFile(model, bytes);
const names = [
  'TESSELATION',
  'FACE_OVAL',
  'LEFT_EYE',
  'RIGHT_EYE',
  'LEFT_EYEBROW',
  'RIGHT_EYEBROW',
  'LIPS',
  'LEFT_IRIS',
  'RIGHT_IRIS',
];
const connections = Object.fromEntries(
  names.map((name) => [name, FaceLandmarker[`FACE_LANDMARKS_${name}`]]),
);
await mkdir('src/vision', { recursive: true });
await writeFile('src/vision/connections.json', JSON.stringify(connections));

const temporary = await mkdtemp(path.join(tmpdir(), 'psl-vision-'));
try {
  const worker = path.join(temporary, 'vision-worker.js');
  await build({
    entryPoints: ['src/vision/worker.ts'],
    outfile: worker,
    bundle: true,
    format: 'iife',
    target: 'es2022',
    minify: true,
    legalComments: 'eof',
  });
  const resources = new Map([
    ['vision-worker.js', await readFile(worker)],
    ['models/face_landmarker.task', bytes],
  ]);
  // The installed resolver's default useModule=false needs only these two classic pairs.
  for (const variant of ['', '_nosimd']) {
    for (const extension of ['js', 'wasm']) {
      const name = `vision_wasm${variant}_internal.${extension}`;
      resources.set(
        `wasm/${name}`,
        await readFile(`node_modules/@mediapipe/tasks-vision/wasm/${name}`),
      );
    }
  }
  const hash = createHash('sha256');
  for (const [name, content] of [...resources].sort(([a], [b]) => a.localeCompare(b)))
    hash.update(name).update(content);
  const revision = hash.digest('hex').slice(0, 16);
  const assetBase = `/vision/${revision}`;
  const destination = `public${assetBase}`;
  await mkdir(destination, { recursive: true });
  for (const [name, content] of resources) {
    await mkdir(path.dirname(`${destination}/${name}`), { recursive: true });
    await writeFile(`${destination}/${name}`, content);
  }
  // This entire directory is generated. Preserve only the current immutable revision.
  for (const entry of await readdir('public/vision'))
    if (entry !== revision) await rm(`public/vision/${entry}`, { recursive: true, force: true });
  // Remove only known legacy generated resources, preserving any unrelated public files.
  await rm('public/vision-worker.js', { force: true });
  await rm('public/models/face_landmarker.task', { force: true });
  for (const variant of ['', '_nosimd', '_module'])
    for (const extension of ['js', 'wasm'])
      await rm(`public/wasm/vision_wasm${variant}_internal.${extension}`, { force: true });
  const manifest = `/* Generated by assets:prepare. Do not import this module from worker.ts. */
export const RUNTIME_ASSETS = ${JSON.stringify({ revision, workerUrl: `${assetBase}/vision-worker.js`, assetBase })} as const;
export interface OfflineAssetStatus { revision: string; ready: boolean; missing: string[] }
export async function getOfflineAssetStatus(): Promise<OfflineAssetStatus | null> {
  if (!('serviceWorker' in navigator) || !navigator.serviceWorker.controller) return null;
  // Same SIMD feature probe used by the pinned MediaPipe FilesetResolver.
  const probe = new Uint8Array([0,97,115,109,1,0,0,0,1,5,1,96,0,1,123,3,2,1,0,10,10,1,8,0,65,0,253,15,253,98,11]);
  let variant = 'nosimd';
  try { await WebAssembly.instantiate(probe); variant = 'simd'; } catch { /* Keep classic noSIMD. */ }
  return new Promise(resolve => {
    const channel = new MessageChannel();
    const timeout = setTimeout(() => { channel.port1.close(); resolve(null); }, 2000);
    channel.port1.onmessage = event => {
      clearTimeout(timeout);
      channel.port1.close();
      resolve(event.data);
    };
    navigator.serviceWorker.controller?.postMessage({ type: 'PSL_CACHE_STATUS', revision: RUNTIME_ASSETS.revision, variant }, [channel.port2]);
  });
}
`;
  await writeFile('src/vision/runtime-assets.ts', manifest);
  console.log(
    `Vision ${revision}: ${resources.size} immutable local files, ${[...resources.values()].reduce((total, content) => total + content.length, 0)} bytes. Model SHA-256 verified.`,
  );
} finally {
  await rm(temporary, { recursive: true, force: true });
}
